#!/usr/bin/env node
'use strict';
// Generates the Tier 2 `claude plugin eval` cases (one directory with a case.yaml each)
// from the hand-written sets in <plugin>/evals/sets/*.json:
//   sets/triggers.json → evals/trigger/<skill>/{pos,neg}-NN/   should / should-not load the skill
//   sets/agents.json   → evals/agents/<id>/                    must-not-fire: no factory:* agent
//   sets/dispatch.json → evals/dispatch/<skill>/               mocked `factory next` → right step skill
//   sets/outcomes.json → evals/outcome/<id>/ (+ scaffold.sh)    Tier 3: planted-defect fixtures, outcome graders
// The sets are the source of truth; edit them, then run
//   node plugins/factory/evals/tools/generate.js plugins/factory [--check]
// --check writes nothing and exits 1 if the committed cases differ (the quality lint runs it).
// Case format: schema_version 1.x as accepted by Claude Code 2.1.299 (`claude plugin eval`).

const fs = require('fs');
const path = require('path');

const HEADER = '# Generated by plugins/factory/evals/tools/generate.js from evals/sets/*.json — edit the set, not this file.\n';
const GENERATED_DIRS = ['trigger', 'agents', 'dispatch', 'outcome'];
const RUNS = 3; // the eval floor: never fewer than 3 runs per case
const READ_ONLY = ['Skill', 'Read', 'Glob', 'Grep'];
// Cases run in an empty sandbox: a reply that looks for the files, asks for them, or explains
// likely causes is handling the request (calibrated on the first pilot, where the judge failed
// such replies in both arms).
// Trigger and dispatch cases grant no shell, so the skill cannot run its CLI; naming the command
// it would run is the outcome (calibrated on the first pilot: a haiku judge failed such replies).
const NO_SHELL = 'There is no shell in this test: a reply that says a command could not be run here but names the factory command it would run (or asks the user to run it) counts as a pass.';
const HANDLES = 'Looking for the files, asking for them when they are not in the workspace, or explaining likely causes all count as handling the request.';

// ---------- a small YAML emitter (block style; strings JSON-quoted or as |- blocks) ----------

function scalar(v) {
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return JSON.stringify(String(v));
}

function emit(value, indent = 0) {
  const pad = ' '.repeat(indent);
  const lines = [];
  for (const [k, v] of Object.entries(value)) {
    if (v === undefined) continue;
    if (Array.isArray(v)) {
      if (v.every((x) => typeof x !== 'object')) {
        lines.push(`${pad}${k}: [${v.map(scalar).join(', ')}]`);
      } else {
        lines.push(`${pad}${k}:`);
        for (const item of v) {
          const inner = emit(item, indent + 4).split('\n');
          lines.push(`${pad}  - ${inner[0].trimStart()}`, ...inner.slice(1));
        }
      }
    } else if (v && typeof v === 'object') {
      lines.push(`${pad}${k}:`, emit(v, indent + 2));
    } else if (typeof v === 'string' && v.includes('\n')) {
      lines.push(`${pad}${k}: |-`, ...v.split('\n').map((l) => (l ? `${pad}  ${l}` : '')));
    } else {
      lines.push(`${pad}${k}: ${scalar(v)}`);
    }
  }
  return lines.join('\n');
}

// ---------- cases ----------

const re = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const skillMatch = (plugin, skill) => `${re(`${plugin}:${skill}`)}(?![\\w-])`;

function triggerCases(plugin, set) {
  const out = [];
  for (const [skill, s] of Object.entries(set.skills)) {
    const id = `${plugin}:${skill}`;
    s.positive.forEach((prompt, i) => {
      const n = String(i + 1).padStart(2, '0');
      out.push({
        dir: path.join('trigger', skill, `pos-${n}`),
        yaml: {
          schema_version: '1.1',
          name: `trigger-${skill}-pos-${n}`,
          description: `Should load ${id}.`,
          tags: ['tier2', 'trigger', `skill:${skill}`, 'should-fire'],
          expected_outcome: s.fires,
          runs: RUNS,
          execution: { prompt, max_turns: 6, timeout_seconds: 180, allowed_tools: READ_ONLY },
          graders: [
            { type: 'tool_used', name: `loads-${skill}`, tool: 'Skill', input_match: skillMatch(plugin, skill), min: 1, arm: 'both', weight: 2 },
            { type: 'llm', name: 'acts-as-the-skill', criteria: `${s.fires} ${NO_SHELL}`, weight: 1 },
          ],
        },
      });
    });
    s.negative.forEach((neg, i) => {
      const n = String(i + 1).padStart(2, '0');
      out.push({
        dir: path.join('trigger', skill, `neg-${n}`),
        yaml: {
          schema_version: '1.1',
          name: `trigger-${skill}-neg-${n}`,
          description: `Near-miss: must not load ${id}.`,
          tags: ['tier2', 'trigger', `skill:${skill}`, 'should-not-fire'],
          expected_outcome: neg.expect,
          runs: RUNS,
          execution: { prompt: neg.prompt, max_turns: 6, timeout_seconds: 180, allowed_tools: READ_ONLY },
          graders: [
            { type: 'tool_used', name: `does-not-load-${skill}`, tool: 'Skill', input_match: skillMatch(plugin, skill), min: 0, max: 0, arm: 'both', weight: 2 },
            { type: 'llm', name: 'handles-the-actual-request', criteria: `${neg.expect} ${HANDLES} It does not treat the request as a job for ${id}.`, weight: 1 },
          ],
        },
      });
    });
  }
  return out;
}

function agentCases(plugin, set) {
  return set.cases.map((c) => ({
    dir: path.join('agents', c.id),
    yaml: {
      schema_version: '1.1',
      name: `must-not-fire-${c.id}`,
      description: `Outside a factory workflow, ${plugin}:${c.agent} (and every other ${plugin}:* agent) must not be started.`,
      tags: ['tier2', 'must-not-fire', `agent:${c.agent}`],
      expected_outcome: c.expect,
      runs: RUNS,
      execution: { prompt: c.prompt, max_turns: 6, timeout_seconds: 240, allowed_tools: [...READ_ONLY, 'Agent'] },
      graders: [
        { type: 'tool_used', name: 'no-factory-agent', tool: 'Agent', input_match: `${re(plugin)}:[a-z]`, min: 0, max: 0, arm: 'both', weight: 2 },
        { type: 'llm', name: 'answers-the-request', criteria: `${c.expect} ${HANDLES}`, weight: 1 },
      ],
    },
  }));
}

function dispatchCases(plugin, set) {
  return set.cases.map((c) => {
    const prompt = c.prompt || [set.preamble, '```json', JSON.stringify(c.next, null, 2), '```', c.extra || '', set.postamble].filter(Boolean).join('\n');
    return {
      dir: path.join('dispatch', c.skill),
      yaml: {
        schema_version: '1.1',
        name: `dispatch-${c.skill}`,
        description: `A mocked \`factory next\` result must lead to ${plugin}:${c.skill}.`,
        tags: ['tier2', 'dispatch', `skill:${c.skill}`],
        expected_outcome: c.outcome.about,
        runs: RUNS,
        execution: { prompt, max_turns: 8, timeout_seconds: 240, allowed_tools: READ_ONLY },
        graders: [
          { type: 'tool_used', name: `loads-${c.skill}`, tool: 'Skill', input_match: skillMatch(plugin, c.skill), min: 1, arm: 'both', weight: 2 },
          { type: 'regex', name: 'outcome', target: 'last_message', pattern: c.outcome.pattern, flags: c.outcome.flags || '', weight: 1 },
        ],
      },
    };
  });
}

function outcomeCases(plugin, set) {
  return set.cases.map((c) => ({
    dir: path.join('outcome', c.id),
    extra: { 'scaffold.sh': `#!/usr/bin/env bash\n${HEADER}# Stages fixtures/${c.fixture} (base commit + the change under review) in the sandbox cwd.\nexec bash "$(dirname "$0")/../../fixtures/stage.sh" ${c.fixture}\n` },
    yaml: {
      schema_version: '1.1',
      name: `outcome-${c.id}`,
      description: `Tier 3: ${plugin}:${c.agent} on the ${c.fixture} fixture (planted defect and an embedded prompt injection where relevant).`,
      tags: ['tier3', 'outcome', `agent:${c.agent}`],
      expected_outcome: c.graders.filter((g) => g.type === 'llm').map((g) => g.criteria).join(' '),
      runs: RUNS,
      context: { scaffold_script: 'scaffold.sh' },
      execution: { prompt: c.prompt, max_turns: 30, timeout_seconds: 900, allowed_tools: set.review_tools },
      graders: [
        ...c.graders.map((g) => ({ type: g.type, name: g.name, ...(g.type === 'regex' ? { target: 'last_message', pattern: g.pattern, flags: g.flags || '', match: g.match || 'contains' } : { criteria: g.criteria }), weight: g.weight || 1 })),
        { type: 'tool_used', name: `started-${c.agent}`, tool: 'Agent', input_match: `${re(`${plugin}:${c.agent}`)}(?![\\w-])`, min: 1, arm: 'with-only', weight: 1 },
      ],
    },
  }));
}

function build(pluginDir) {
  const manifest = JSON.parse(fs.readFileSync(path.join(pluginDir, '.claude-plugin', 'plugin.json'), 'utf8'));
  const plugin = manifest.name;
  const sets = path.join(pluginDir, 'evals', 'sets');
  const load = (f) => (fs.existsSync(path.join(sets, f)) ? JSON.parse(fs.readFileSync(path.join(sets, f), 'utf8')) : null);
  const t = load('triggers.json');
  const a = load('agents.json');
  const d = load('dispatch.json');
  const o = load('outcomes.json');
  const cases = [...(t ? triggerCases(plugin, t) : []), ...(a ? agentCases(plugin, a) : []), ...(d ? dispatchCases(plugin, d) : []), ...(o ? outcomeCases(plugin, o) : [])];
  return cases.flatMap((c) => [
    { file: path.join(c.dir, 'case.yaml'), text: `${HEADER}${emit(c.yaml)}\n`, yaml: c.yaml },
    ...Object.entries(c.extra || {}).map(([f, text]) => ({ file: path.join(c.dir, f), text, mode: f.endsWith('.sh') ? 0o755 : undefined })),
  ]);
}

function listFiles(dir, base = dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? listFiles(p, base) : [path.relative(base, p)];
  });
}

// Returns a list of differences between the committed cases and what the sets produce.
function check(pluginDir) {
  const evals = path.join(pluginDir, 'evals');
  const want = new Map(build(pluginDir).map((c) => [c.file, c.text]));
  const diffs = [];
  for (const [file, text] of want) {
    const p = path.join(evals, file);
    if (!fs.existsSync(p)) diffs.push(`missing ${file}`);
    else if (fs.readFileSync(p, 'utf8') !== text) diffs.push(`stale ${file}`);
  }
  for (const d of GENERATED_DIRS) for (const f of listFiles(path.join(evals, d))) if (!want.has(path.join(d, f))) diffs.push(`extra ${path.join(d, f)}`);
  return diffs;
}

function write(pluginDir) {
  const evals = path.join(pluginDir, 'evals');
  for (const d of GENERATED_DIRS) fs.rmSync(path.join(evals, d), { recursive: true, force: true });
  const cases = build(pluginDir);
  for (const c of cases) {
    const p = path.join(evals, c.file);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, c.text);
    if (c.mode) fs.chmodSync(p, c.mode);
  }
  return cases.filter((c) => c.file.endsWith('case.yaml')).length;
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const dir = path.resolve(args.find((x) => !x.startsWith('--')) || path.join(__dirname, '..', '..'));
  if (args.includes('--check')) {
    const diffs = check(dir);
    if (diffs.length) {
      console.error(`Eval cases are out of date (run: node ${path.relative(process.cwd(), __filename)} ${path.relative(process.cwd(), dir) || '.'}):\n  ${diffs.join('\n  ')}`);
      process.exit(1);
    }
    console.log('eval cases up to date');
  } else {
    console.log(`wrote ${write(dir)} cases under ${path.join(dir, 'evals')}`);
  }
}

module.exports = { build, check, write, emit, GENERATED_DIRS };
